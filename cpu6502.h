enum {
  FLAG_N = 0b10000000,
  FLAG_V = 0b1000000,
  FLAG_U = 0b100000,
  FLAG_B = 0b10000,
  FLAG_D = 0b1000,
  FLAG_I = 0b100,
  FLAG_Z = 0b10,
  FLAG_C = 0b1
};

typedef struct CPU {
  uint8_t regA;
  uint8_t regX;
  uint8_t regY;
  uint8_t regS;
  uint8_t regP;

  uint8_t regPCL;
  uint8_t regPCH;
  uint8_t opcode;

  Bus *bus;
  bool irqLine;
  bool nmiPending;

  uint64_t steps;
} CPU;

CPU *cpu_init_cpu(Bus *bus);
void cpu_execute_cpu(CPU *ctx);
void cpu_deinit_cpu(CPU *ctx);

